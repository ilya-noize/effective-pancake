package com.example.order;

public enum OrderStatus {
    PENDING,
    // Заказ создан, но оплата ещё не получена либо идёт подготовка к отправке. На этом этапе заказ можно отменить.

    PROCESSING,
    // Оплата подтверждена, продавец приступил к обработке заказа (сборке, упаковке). Отмена обычно уже невозможна.

    IN_QUEUE,
    // Товары зарезервированы, заказ готов к сборке и упаковке.

    IN_PROCESS,
    // Заказ в работе: идёт сборка, упаковка или подготовка к отправке. Изменения уже не допускаются.

    ON_HOLD,
    // Обработка приостановлена — например, из‑за необходимости уточнить данные у клиента или внести изменения в заказ.

    BACK_ORDER,
    // Один или несколько товаров отсутствуют на складе. Отправка будет возможна после пополнения запасов.

    SHIPPED,
    // Посылка отправлена: этикетка с трекингом создана, перевозчик взял груз в работу.

    AWAITING_PICKUP,
    // Этикетка создана, но перевозчик ещё не забрал посылку.

    IN_TRANSIT,
    // Перевозчик забрал посылку и указывает ориентировочную дату доставки.

    DELAYED,
    // Доставка задерживается по причинам, связанным с перевозчиком.

    NOTICE_LEFT,
    // Перевозчик оставил уведомление — нужно согласовать забор посылки или повторную доставку.

    AVAILABLE_FOR_PICKUP,
    // Посылка доступна для самовывоза в пункте выдачи перевозчика.

    OUT_FOR_DELIVERY,
    // Посылка в пути — должна быть доставлена в текущий день.

    DELIVERED,
    // Посылка успешно доставлена получателю.

    PARTIALLY_FULFILLED,
    // Часть товаров отправлена, остальные ожидаются (например, из‑за бэк-ордера).

    FULFILLED,
    // Все товары упакованы и переданы в доставку. Для уточнения статуса нужно проверить трекинг.

    UNFULFILLED,
    // Ни один из товаров ещё не добавлен в отправку.

    CANCELED,
    // Заказ отменён и исключён из процесса обработки. Товары сняты с резерва.

    COMPLETED,
    // Все позиции заказа доставлены и приняты клиентом.

    ERROR,
    // Возникла проблема с заказом (например, ошибка при обработке платежа или сборке).

    EXCEPTION,
    // Ошибка в процессе выполнения (например, неверный адрес, недоступность локации). Требуется проверка системы доставки.

    JOINED
    // Заказ объединён с другим заказом на тот же адрес для совместной отправки.
}


